// Keeps THIRD_PARTY_NOTICES.md, the single register of everything Palinopsia
// borrows, complete. Two modes :
//
//   node scripts/notices.mjs          (npm run notices)        regenerate licenses/npm-dependencies.txt
//   node scripts/notices.mjs --check  (npm run check:notices)  fail if anything is missing or stale
//
// The check fails when :
//   1. licenses/npm-dependencies.txt no longer matches the installed runtime dependencies;
//   2. a font in src/renderer/src/fonts is not listed in licenses/fonts.txt;
//   3. a vendored or shipped third-party folder (native/*/sdk/*, resources/*) is not
//      named in THIRD_PARTY_NOTICES.md;
//   4. a `third-party: <name>` tag in the code names something THIRD_PARTY_NOTICES.md
//      does not contain;
//   5. a file carries a foreign copyright line, an SPDX id or a Shadertoy link but no
//      `third-party:` tag (so it cannot be traced to its entry).
//
// The rule it backs : code, shaders, algorithms ported line by line, binaries, models,
// fonts, images, sounds and data taken from someone else get an entry in
// THIRD_PARTY_NOTICES.md (with the license text when the license asks for it) in the
// same commit that brings them in, and a `third-party: <entry name>` comment where
// they are used. Ideas and published methods get a credit there too.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/')
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8')
const CHECK = process.argv.includes('--check')
const NOTICES = read('THIRD_PARTY_NOTICES.md')
const problems = []

// ── 1. npm runtime dependencies ─────────────────────────────────────────────
// Everything npm installs for production ships in the app (main process, preload),
// plus the dev dependencies Vite bundles into the renderer (React).
const BUNDLED_DEV = ['react', 'react-dom', 'scheduler', 'loose-envify', 'js-tokens']

function npmDependencies() {
  const lock = JSON.parse(read('package-lock.json'))
  const entries = []
  for (const [key, v] of Object.entries(lock.packages)) {
    if (!key.startsWith('node_modules/')) continue
    const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length)
    if (v.dev && !BUNDLED_DEV.includes(name)) continue
    // Optional packages are per-OS binaries (koffi's, esbuild's…) : only one OS
    // installs each, so they are listed from the lockfile alone (no file text),
    // and the generated file comes out the same on every OS.
    const dir = path.join(ROOT, key)
    let license = v.license || ''
    let text = ''
    if (v.optional) text = `(a per-OS binary package of a dependency above, under the same terms : ${license || 'see its package'})`
    else if (fs.existsSync(dir)) {
      try {
        const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
        license = pj.license || (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type).join(' OR ') : license)
      } catch {}
      const lf = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$|-)/i.test(f))
      if (lf) text = fs.readFileSync(path.join(dir, lf), 'utf8').replace(/\r\n/g, '\n').trim()
    }
    // No license field : read it from the license file itself.
    if (!license && /^\s*(the )?MIT License/i.test(text)) license = 'MIT (from its LICENSE file)'
    entries.push({ name, version: v.version, license: license || 'UNKNOWN', text })
  }
  entries.sort((a, b) => (a.name + a.version).localeCompare(b.name + b.version))
  const seen = new Set()
  const out = [
    'npm packages shipped with Palinopsia',
    '====================================',
    '',
    'Generated by scripts/notices.mjs from package-lock.json : do not edit by hand,',
    'run `npm run notices` after any dependency change. Each package keeps its own',
    'license; its license file is reproduced below as the package distributes it.',
    ''
  ]
  for (const e of entries) {
    const id = `${e.name}@${e.version}`
    if (seen.has(id)) continue
    seen.add(id)
    out.push('-'.repeat(78), `${id}  (${e.license})`, '')
    out.push(e.text || `(this package ships no license file; its package.json declares ${e.license})`, '')
    if (!/MIT|ISC|BSD|Apache|Unlicense|0BSD|CC0|GPL|Python|BlueOak|Zlib/i.test(e.license))
      problems.push(`npm package ${id} has an unrecognised license "${e.license}" : review it and credit it by hand`)
  }
  return out.join('\n') + '\n'
}

const npmText = npmDependencies()
const NPM_FILE = 'licenses/npm-dependencies.txt'
if (CHECK) {
  const cur = fs.existsSync(path.join(ROOT, NPM_FILE)) ? read(NPM_FILE) : ''
  if (cur !== npmText) problems.push(`${NPM_FILE} is stale : run \`npm run notices\` and commit it`)
} else {
  fs.writeFileSync(path.join(ROOT, NPM_FILE), npmText)
  console.log(`wrote ${NPM_FILE}`)
}

// ── 2. fonts ────────────────────────────────────────────────────────────────
const fontList = read('licenses/fonts.txt')
for (const f of fs.readdirSync(path.join(ROOT, 'src/renderer/src/fonts'))) {
  if (!/\.(ttf|otf|woff2?)$/i.test(f)) continue
  if (!fontList.includes(`${f} :`)) problems.push(`font ${f} is not listed (with its copyright and license) in licenses/fonts.txt`)
}

// ── 3. vendored and shipped third-party folders ─────────────────────────────
const shipped = []
for (const n of fs.readdirSync(path.join(ROOT, 'native'))) {
  const sdk = path.join(ROOT, 'native', n, 'sdk')
  if (fs.existsSync(sdk)) for (const s of fs.readdirSync(sdk)) if (fs.statSync(path.join(sdk, s)).isDirectory()) shipped.push(`native/${n}/sdk/${s}`)
  if (fs.existsSync(sdk) && fs.readdirSync(sdk).some((s) => fs.statSync(path.join(sdk, s)).isFile())) shipped.push(`native/${n}/sdk`)
}
for (const r of fs.readdirSync(path.join(ROOT, 'resources'))) if (fs.statSync(path.join(ROOT, 'resources', r)).isDirectory()) shipped.push(`resources/${r}`)
for (const p of shipped) if (!NOTICES.includes(p)) problems.push(`${p} ships third-party material but THIRD_PARTY_NOTICES.md never names it`)

// ── 4 + 5. tags in the code ─────────────────────────────────────────────────
const SCAN = ['src', 'tools', 'scripts', 'native']
const EXT = /\.(ts|tsx|js|mjs|cjs|fs|vs|glsl|py|sh|cpp|cc|h|mm|c)$/
const SKIP = /(^|\/)(node_modules|build|out|sdk|\.syphon-src|\.syphon-build|frameworks)(\/|$)|tools\/shader-rig\/bundle\.js$|scripts\/notices\.mjs$/
const FOREIGN = /shadertoy\.com\/view|SPDX-License-Identifier|copyright\s*(\(c\)|©)\s*(?!\d{4}\s*(vincent fillion|filliformes))/i
function walk(d, acc) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f)
    if (SKIP.test(rel(p))) continue
    const st = fs.statSync(p)
    if (st.isDirectory()) walk(p, acc)
    else if (EXT.test(f)) acc.push(p)
  }
  return acc
}
let tags = 0
for (const p of SCAN.flatMap((d) => walk(path.join(ROOT, d), []))) {
  const src = fs.readFileSync(p, 'utf8')
  // The entry name is the tag up to an optional note in parentheses.
  const found = [...src.matchAll(/third-party:\s*([^\n*(]+?)\s*(?:\(|\*\/|\n|$)/g)].map((m) => m[1].trim())
  tags += found.length
  for (const t of found) if (!NOTICES.includes(t)) problems.push(`${rel(p)} : tag "third-party: ${t}" has no matching entry in THIRD_PARTY_NOTICES.md`)
  if (!found.length && FOREIGN.test(src)) problems.push(`${rel(p)} carries a foreign copyright, an SPDX id or a Shadertoy link but no \`third-party:\` tag`)
}

if (problems.length) {
  console.error(`THIRD_PARTY_NOTICES check failed (${problems.length}) :\n  - ` + problems.join('\n  - '))
  process.exit(1)
}
console.log(`notices ok : ${npmText.split('\n' + '-'.repeat(78) + '\n').length - 1} npm packages, ${shipped.length} shipped folders, ${tags} third-party tags`)
